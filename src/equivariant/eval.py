from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import torch

from equivariant.const import (
    ANGLES,
    BATCH,
    FAMILIES,
    IMG,
    N_CLASSES,
    N_ROT,
    N_TEST,
    N_TRAIN,
    STEPS,
    WIDTH,
)
from equivariant.data import chance_pct
from equivariant.models import params_total


@torch.no_grad()
def accuracy(model, images: np.ndarray, labels: np.ndarray) -> float:
    model.eval()
    hits = 0
    n = 0
    for i in range(0, len(labels), BATCH):
        xb = images[i : i + BATCH]
        yb = labels[i : i + BATCH]
        xt = torch.from_numpy(xb[:, None, :, :].astype(np.float32))
        pred = model(xt).argmax(-1).cpu().numpy()
        hits += int((pred == yb).sum())
        n += len(yb)
    return hits / max(n, 1)


def family_row(model, name: str, upright, y, rotated) -> dict:
    up = round(100.0 * accuracy(model, upright, y), 2)
    rot = round(100.0 * accuracy(model, rotated, y), 2)
    return {
        "family": name,
        "attach": getattr(model, "attach", "plain_conv"),
        "group": getattr(model, "group", "none") if name != "cnn_aug" else "none",
        "params_total": int(params_total(model)),
        "upright_pct": up,
        "rotated_pct": rot,
        "aug": name == "cnn_aug",
    }


def bake_off(rows: list[dict], illustrative: bool = False, blocker: str | None = None) -> dict:
    by = {r["family"]: r for r in rows}
    eq = by["equivariant"]
    cnn = by["cnn"]
    aug = by.get("cnn_aug", {})
    return {
        "success_pct": eq["rotated_pct"],
        "cnn_rotated_pct": cnn["rotated_pct"],
        "cnn_pct": cnn["rotated_pct"],
        "upright_pct": eq["upright_pct"],
        "cnn_upright_pct": cnn["upright_pct"],
        "cnn_aug_rotated_pct": aug.get("rotated_pct", 0.0),
        "chance_pct": round(chance_pct(), 2),
        "n_classes": N_CLASSES,
        "n_train": N_TRAIN,
        "n_test": N_TEST,
        "steps": STEPS,
        "width": WIDTH,
        "img": IMG,
        "n_rot": N_ROT,
        "angles": list(ANGLES),
        "families": rows,
        "illustrative": illustrative,
        "blocker": blocker,
        "train_families": list(FAMILIES),
    }


def write_data_ts(m: dict, path: str = "web/src/metrics.gen.ts") -> None:
    if not Path("web/src").exists():
        return
    families = [
        {
            "family": r["family"],
            "attach": r["attach"],
            "group": r["group"],
            "paramsTotal": int(r["params_total"]),
            "uprightPct": float(r["upright_pct"]),
            "rotatedPct": float(r["rotated_pct"]),
            "aug": bool(r["aug"]),
        }
        for r in m["families"]
    ]
    body = f"""// Generated by scripts/run.py. Numbers match metrics.json. Do not hand-edit.

export const ILLUSTRATIVE = {str(bool(m.get("illustrative"))).lower()}

export const PROTOCOL = {{
  nClasses: {int(m["n_classes"])},
  nTrain: {int(m["n_train"])},
  nTest: {int(m["n_test"])},
  steps: {int(m["steps"])},
  width: {int(m["width"])},
  img: {int(m["img"])},
  nRot: {int(m["n_rot"])},
  angles: {json.dumps(m["angles"])},
}}

export const METRICS = {{
  successPct: {float(m["success_pct"])},
  cnnRotatedPct: {float(m["cnn_rotated_pct"])},
  uprightPct: {float(m["upright_pct"])},
  cnnUprightPct: {float(m["cnn_upright_pct"])},
  cnnAugRotatedPct: {float(m["cnn_aug_rotated_pct"])},
  chancePct: {float(m["chance_pct"])},
}}

export type FamilyRow = {{
  family: string
  attach: string
  group: string
  paramsTotal: number
  uprightPct: number
  rotatedPct: number
  aug: boolean
}}

export const FAMILIES: FamilyRow[] = {json.dumps(families, indent=2)}
"""
    Path(path).write_text(body, encoding="utf-8")
    print(f"wrote {path}")


def write_metrics(m: dict, path: str = "metrics.json") -> None:
    Path(path).write_text(json.dumps(m, indent=2), encoding="utf-8")
    Path("data").mkdir(exist_ok=True)
    Path("data/metrics.json").write_text(json.dumps(m, indent=2), encoding="utf-8")


def print_report(m: dict) -> None:
    print(f"{'family':<14} {'upright_pct':>12} {'rotated_pct':>12} {'chance_pct':>11}")
    chance = m["chance_pct"]
    for r in m["families"]:
        print(f"{r['family']:<14} {r['upright_pct']:>12.1f} {r['rotated_pct']:>12.1f} {chance:>11.1f}")
    print(
        f"rotated_pct={m['success_pct']:.1f} cnn_pct={m['cnn_pct']:.1f} "
        f"chance_pct={chance:.1f} upright_pct={m['upright_pct']:.1f}"
    )
